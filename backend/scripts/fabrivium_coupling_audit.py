# What is scanned

# Directories that never contain hand-written source.
_SKIP_DIRS = {
    ".git", "node_modules", "__pycache__", "dist", "build",
    ".pytest_cache", ".hypothesis", ".venv", "venv", ".mypy_cache",
    ".playwright-mcp", ".ruff_cache",
}

# Extensions worth reading.
_SCAN_EXT = {".py", ".ts", ".tsx", ".js", ".mjs", ".jsx", ".json", ".md", ".txt", ".css", ".html"}

# Files above this size are data dumps (recorded runs, transcripts), not code.
_LARGE_FILE_BYTES = 2_000_000


# What is looked for

@dataclass(frozen=True)
class Token:
    """One coupling probe."""

    name: str
    pattern: re.Pattern[str]
    # What this probe is evidence of, printed in the report.
    meaning: str


def _rx(pattern: str) -> re.Pattern[str]:
    return re.compile(pattern, re.IGNORECASE)


# The brief's search list, as anchored patterns.
TOKENS: tuple[Token, ...] = (
    Token("CEC-120", _rx(r"\bCEC[-\s]?120\b"), "the golden product's identity"),
    Token("golden figures", _rx(r"\b(1[, ]?900|1[, ]?435|1[, ]?058|2[, ]?033|465)\b"),
          "target / baseline / gap / measured throughput of the golden run"),
    Token("golden cost", _rx(r"\b(18[, ]?000|18k)\b"), "the golden run's OPEX figure"),
    Token("golden operations", _rx(r"\b(cable connection|screw fastening|PCB placement|visual inspection)\b"),
          "operation names generated by the golden route"),
    Token("domain vocabulary", _rx(r"\b(screwdriv\w*|PCB|soldering|palletiz\w*)\b"),
          "electronics/bench-assembly process vocabulary"),
    Token("golden schedule", _rx(r"\b(2 shifts|8 operators|7 stations|30 ?[x×] ?18)\b"),
          "the golden run's schedule, workforce and floor"),
    Token("golden run counts", _rx(r"\b(23 simulations|3 strategies)\b"), "the golden run's reported activity"),
    Token("plan labels", _rx(r"\bPlan [ABC]\b"), "display labels for interventions"),
    Token("demo vocabulary", _rx(r"\b(golden[_ -]?run|demo[_ -]?mode|demoStage|example[_ -]?data|test fixture)\b"),
          "demonstration scaffolding"),
)

# Probes whose production occurrences are DOMAIN COVERAGE, not Golden-Run coupling.
_DOMAIN_TOKENS = frozenset({"domain vocabulary"})

# Class F probes: a production BRANCH keyed on the demo or on a product identity.
_CONTROL_FLOW: tuple[re.Pattern[str], ...] = (
    _rx(r"\bif\b[^\n]{0,80}\b(is_demo|demo_mode|golden|cec[-_]?120)\b"),
    _rx(r"\b(product_name|productName|product\.name)\s*[=!]=\s*['\"]"),
    # A COUNT assumption, e.g.
    _rx(r"\b(operations|stages|stations|machines)\s*\.\s*length\s*===?\s*[1-9]"),
    _rx(r"\blen\(\s*(operations|stages|stations|machines)[^)]*\)\s*==\s*[1-9]"),
)


# Zone: where does this file live?

PRODUCTION = "production"
TEST = "test"
EXAMPLE = "example"
DOCUMENTATION = "documentation"


def zone_of(rel: pathlib.PurePosixPath) -> str:
    parts = rel.parts
    name = rel.name

    if parts and parts[0] in {"examples", "demo", "presentation", "projects", "exports", "simulation", "tests"}:
        return EXAMPLE
    if parts[:2] == ("backend", "tests") or parts[:2] == ("backend", "scripts"):
        return TEST if parts[1] == "tests" else EXAMPLE
    if ".test." in name or ".spec." in name:
        return TEST
    if parts[:3] == ("frontend", "src", "test"):
        return TEST
    if rel.suffix == ".md":
        return DOCUMENTATION
    if parts[:2] == ("backend", "app") or parts[:2] == ("frontend", "src"):
        return PRODUCTION
    if parts[:1] == ("docs",):
        return DOCUMENTATION
    return EXAMPLE


# Commentary detection — the fact a grep cannot supply

def python_commentary_lines(source: str) -> set[int]:
    """Every 1-based line of *source* that is a comment or a docstring."""
    lines: set[int] = set()
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(source).readline))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return lines

    prev_meaningful: int | None = None
    for tok in tokens:
        if tok.type == tokenize.COMMENT:
            lines.update(range(tok.start[0], tok.end[0] + 1))
        elif tok.type == tokenize.STRING:
            # A docstring is a bare string expression: the previous
            # meaningful token is NEWLINE, INDENT, DEDENT or nothing.
            if prev_meaningful in (None, tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT):
                lines.update(range(tok.start[0], tok.end[0] + 1))
        if tok.type not in (tokenize.NL, tokenize.COMMENT):
            prev_meaningful = tok.type
    return lines


_TS_LINE_COMMENT = re.compile(r"^\s*(//|\*|/\*)")


def ts_commentary_lines(source: str) -> set[int]:
    """Approximate comment lines for TypeScript/JavaScript."""
    lines: set[int] = set()
    in_block = False
    for number, line in enumerate(source.splitlines(), start=1):
        if in_block:
            lines.add(number)
            if "*/" in line:
                in_block = False
            continue
        stripped = line.strip()
        if _TS_LINE_COMMENT.match(stripped):
            lines.add(number)
        if "/*" in line and "*/" not in line.split("/*", 1)[1]:
            in_block = True
            lines.add(number)
    return lines


def commentary_lines(path: pathlib.Path, source: str) -> set[int]:
    if path.suffix == ".py":
        return python_commentary_lines(source)
    if path.suffix in {".ts", ".tsx", ".js", ".jsx", ".mjs"}:
        return ts_commentary_lines(source)
    if path.suffix == ".css":
        # CSS has only /* */ comments, and the TS scanner's block handling
        # covers them exactly (there is no // and no string-quoted opener).
        return ts_commentary_lines(source)
    # Markdown, JSON, plain text: every line is data or prose, never a branch.
    return set()


