@dataclass
class Hit:
    path: str
    line: int
    token: str
    meaning: str
    text: str
    zone: str
    executable: bool
    classification: str
    action: str


@dataclass
class Report:
    hits: list[Hit] = field(default_factory=list)
    files_scanned: int = 0
    unreadable: list[str] = field(default_factory=list)

    def by_class(self) -> dict[str, int]:
        counts: dict[str, int] = {}
        for hit in self.hits:
            counts[hit.classification] = counts.get(hit.classification, 0) + 1
        return counts


def classify(
    path: str,
    zone: str,
    executable: bool,
    text: str,
    control_flow: bool,
    token_name: str,
) -> tuple[str, str]:
    """Return ``(classification, required action)``."""
    if control_flow:
        return CLASS_F, "CRITICAL — a production branch keyed on the demo or a product identity. Remove."

    if zone == TEST:
        return CLASS_A, "None. A fixture may name the golden case; that is what a regression is."
    if zone == EXAMPLE:
        return CLASS_B, "None, while it stays out of the production import graph."
    if zone == DOCUMENTATION:
        return CLASS_C, "None. Prose about a measured run."

    # Production.
    if not executable:
        return CLASS_C, "None. Commentary citing the measured run as a worked example."
    if path in _DECLARED_DEFAULTS:
        return CLASS_D, f"Review only. {_DECLARED_DEFAULTS[path]}"
    if path in _UI_EXAMPLE_COPY:
        return CLASS_C, (
            f"Presentation only ({_UI_EXAMPLE_COPY[path]}). Should become domain-derived "
            "once a project declares its domain, so a packaging project is not prompted "
            "with an electronics example."
        )
    if token_name in _DOMAIN_TOKENS:
        return CLASS_D, (
            "Review as DOMAIN COVERAGE, not coupling: a process-family vocabulary entry. "
            "The question it raises is which domains are covered, not whether the golden "
            "run leaked."
        )
    if _UI_COPY_HINTS.search(text):
        return CLASS_D, (
            "Review. UI placeholder/example copy: presentation-only, but it teaches a new "
            "user the golden run's shape of input. Should be domain-derived where a domain is known."
        )
    return CLASS_E, "MUST REMOVE — an executable production occurrence of a Golden-Run literal."


# Scan

def iter_files(root: pathlib.Path):
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        if any(part in _SKIP_DIRS for part in path.parts):
            continue
        if path.suffix.lower() not in _SCAN_EXT:
            continue
        yield path


def scan(root: pathlib.Path = ROOT) -> Report:
    report = Report()
    for path in iter_files(root):
        rel = pathlib.PurePosixPath(path.relative_to(root).as_posix())
        try:
            source = path.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:  # a file being written by another process
            report.unreadable.append(f"{rel}: {exc}")
            continue

        report.files_scanned += 1
        zone = zone_of(rel)
        big = len(source) > _LARGE_FILE_BYTES

        # Cheap pre-filter: most files contain none of the probes.
        if not any(token.pattern.search(source) for token in TOKENS) and not any(
            rx.search(source) for rx in _CONTROL_FLOW
        ):
            continue

        comments = set() if big else commentary_lines(path, source)

        for number, line in enumerate(source.splitlines(), start=1):
            control_flow = zone == PRODUCTION and any(rx.search(line) for rx in _CONTROL_FLOW)
            matched = [token for token in TOKENS if token.pattern.search(line)]
            if not matched and not control_flow:
                continue

            executable = number not in comments
            token = matched[0] if matched else Token("control flow", _rx("x"), "a branch")
            classification, action = classify(
                str(rel), zone, executable, line, control_flow, token.name
            )
            report.hits.append(
                Hit(
                    path=str(rel),
                    line=number,
                    token=token.name,
                    meaning=token.meaning,
                    text=line.strip()[:200],
                    zone=zone,
                    executable=executable,
                    classification=classification,
                    action=action,
                )
            )
    return report


# Output

def render_markdown(report: Report) -> str:
    out: list[str] = []
    counts = report.by_class()
    out.append("| Class | Occurrences |")
    out.append("|---|---:|")
    for name in (CLASS_A, CLASS_B, CLASS_C, CLASS_D, CLASS_E, CLASS_F):
        out.append(f"| {name} | {counts.get(name, 0)} |")
    out.append("")

    for name in (CLASS_F, CLASS_E, CLASS_D):
        rows = [hit for hit in report.hits if hit.classification == name]
        out.append(f"### {name} — {len(rows)}")
        out.append("")
        if not rows:
            out.append("None.")
            out.append("")
            continue
        out.append("| File | Line | Coupling | Required action |")
        out.append("|---|---:|---|---|")
        for hit in rows:
            text = hit.text.replace("|", "\\|")
            out.append(f"| `{hit.path}` | {hit.line} | {hit.token} — `{text}` | {hit.action} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    # The report quotes source lines, which contain arrow and dash
    # characters the Windows console's default cp1252 cannot encode. Force
    # UTF-8 rather than letting the scan die on a quotation mark.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    parser.add_argument("--markdown", action="store_true", help="audit table")
    args = parser.parse_args(argv)

    report = scan()

    if args.json:
        print(json.dumps({
            "files_scanned": report.files_scanned,
            "counts": report.by_class(),
            "unreadable": report.unreadable,
            "hits": [hit.__dict__ for hit in report.hits],
        }, indent=2))
    elif args.markdown:
        print(render_markdown(report))
    else:
        print(f"scanned {report.files_scanned} files")
        for name, count in sorted(report.by_class().items()):
            print(f"  {name:<32} {count}")
        for hit in report.hits:
            if hit.classification in (CLASS_E, CLASS_F):
                print(f"  !! {hit.path}:{hit.line}  {hit.text}")
        if report.unreadable:
            print(f"  unreadable: {len(report.unreadable)}")

    blocking = sum(1 for hit in report.hits if hit.classification in (CLASS_E, CLASS_F))
    return 1 if blocking else 0


if __name__ == "__main__":
    sys.exit(main())
